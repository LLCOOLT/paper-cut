#!/usr/bin/env python3
"""Generate port/settings/features/cosmetic_textures.inc: which partner each
of the partners' textures is, by its content, for the cosmetics' recolours
(port/settings/features/cosmetics.cpp).

The same texture is in more than one file: a partner's field and battle model
(a/c_windy-), the Party page's (a/EFF_m_cloud-), the menu's all-in-one file
(a/menu_party-) and a few scenes' (a/t_bomt_n-). The masks are written for the
partner's own file's textures, by their place in it; the table names each of
those textures by a hash of its texels and palette, so a texture recoloured is
recoloured wherever the game draws it, in whatever file it is loaded from.

Only hashes are written: no texel of the disc. The three releases' textures
are the same (checked: --check-versions).

  gen_cosmetic_textures.py ISO                    write the table
  gen_cosmetic_textures.py ISO --check            fail if it is out of date
  gen_cosmetic_textures.py ISO --check-versions ISO2 ISO3
"""
import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gcdisc  # noqa: E402

# the owners, in cosmetics.cpp's Owner order
OWNERS = [
    ("kGoombella", "c_pkr"),
    ("kKoops", "c_pnk"),
    ("kBobbery", "c_bomt_n"),
    ("kFlurrie", "c_windy"),
    ("kVivian", "c_vivian"),
    ("kMowz", "c_tyutyu"),
]

# GX texture formats: (block width, block height, bytes per block)
BLOCKS = {
    0: (8, 8, 32),   # I4
    1: (8, 4, 32),   # I8
    2: (8, 4, 32),   # IA4
    3: (4, 4, 32),   # IA8
    4: (4, 4, 32),   # RGB565
    5: (4, 4, 32),   # RGB5A3
    6: (4, 4, 64),   # RGBA8
    8: (8, 8, 32),   # C4
    9: (8, 4, 32),   # C8
    10: (4, 4, 32),  # C14X2
    14: (8, 8, 32),  # CMPR
}

FNV_OFFSET = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3


def fnv(data, h=FNV_OFFSET):
    for b in data:
        h = ((h ^ b) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return h


def texel_bytes(w, h, fmt):
    """the bytes a GX texture's level 0 takes (cosmetics.cpp's texelBytes)"""
    bw, bh, bb = BLOCKS[fmt]
    return ((w + bw - 1) // bw) * ((h + bh - 1) // bh) * bb


def texture_hashes(tpl):
    """[hash] of a TPL file's textures, as cosmetics.cpp's textureHash makes
    them: FNV-1a 64 over width, height and format (one byte each, low bytes),
    the level 0 texels, then the palette's entries"""
    magic, n, tab = struct.unpack_from(">III", tpl, 0)
    if magic != 0x0020AF30:
        raise ValueError("not a TPL file")
    out = []
    for i in range(n):
        th, ph = struct.unpack_from(">II", tpl, tab + 8 * i)
        h, w, fmt, off = struct.unpack_from(">HHII", tpl, th)
        hv = fnv(bytes([w & 255, h & 255, fmt & 255]))
        hv = fnv(tpl[off:off + texel_bytes(w, h, fmt)], hv)
        if ph != 0 and fmt in (8, 9, 10):
            count, _unpacked, _pad, _pfmt, poff = struct.unpack_from(">HBBII", tpl, ph)
            hv = fnv(tpl[poff:poff + count * 2], hv)
        out.append(hv)
    return out


def table(iso):
    d = gcdisc.Disc(iso)
    seen = {}
    rows = []
    for owner, (name, file) in enumerate(OWNERS):
        for index, hv in enumerate(texture_hashes(d.read("a/" + file + "-"))):
            if hv in seen:
                continue  # (the same texture twice: the first is its place)
            seen[hv] = (owner, index)
            rows.append((hv, name, index))
    rows.sort()
    return rows


def render(rows):
    lines = [
        "// Generated by tools/port/gen_cosmetic_textures.py from the disc: do not edit.",
        "// The partners' textures by content (cosmetics.cpp's textureHash): the partner and the",
        "// texture's place in their own file. Hashes only, no texels.",
    ]
    for hv, name, index in rows:
        lines.append(f"{{0x{hv:016X}ull, {name}, {index}}},")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("iso")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--check-versions", nargs="*")
    a = ap.parse_args()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "port", "settings", "features",
                       "cosmetic_textures.inc")
    text = render(table(a.iso))
    if a.check_versions:
        for other in a.check_versions:
            if render(table(other)) != text:
                print(f"{other}: the partners' textures differ from {a.iso}'s")
                return 1
        print("the same in every release given")
        return 0
    if a.check:
        with open(out, encoding="utf-8") as f:
            if f.read() != text:
                print(f"{out} is out of date")
                return 1
        return 0
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
