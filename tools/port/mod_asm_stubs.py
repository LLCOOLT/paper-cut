#!/usr/bin/env python3
"""Stubs for a GameCube mod's assembly routines (docs/MODDING.md, "Porting a
GameCube mod").

A GameCube mod's .s files are PowerPC: they don't build for the PC. Mostly
they are what the mod's code patches branch to (patch::writeBranch and the
like), and the port skips those patches, so a routine only has to exist for
the mod to link. Each `.global` name gets a C function that logs once if it
ever runs; a routine the mod's C++ calls (and the porter has written for the
PC) is left out when a source given with --ported defines it.

  mod_asm_stubs.py --mod DIR [--asm 'source/**/*.s'] [--ported 'port/*.cpp']
                   --out port/asm_stubs.cpp
"""
import argparse
import glob
import os
import re
import struct
import sys

# data directives: their size and how a value packs (native byte order: the
# mod's C++ reads the data as the fields the directives wrote)
DATA = {".byte": (1, "B"), ".2byte": (2, "H"), ".hword": (2, "H"), ".short": (2, "H"), ".half": (2, "H"),
        ".4byte": (4, "I"), ".long": (4, "I"), ".word": (4, "I"), ".int": (4, "I"),
        ".8byte": (8, "Q"), ".quad": (8, "Q"), ".float": (4, "f"), ".single": (4, "f"), ".double": (8, "d")}
STRINGS = {".asciz": True, ".string": True, ".ascii": False}
SPACE = {".space", ".zero", ".skip"}


def value(tok, fmt):
    """A directive's operand as a number (0 for a symbol: an address, which
    has no GameCube meaning here)."""
    tok = tok.strip()
    try:
        v = float(tok) if fmt in "fd" else int(tok, 0)
    except ValueError:
        return 0
    if fmt not in "fd":
        v &= (1 << (8 * struct.calcsize(fmt))) - 1
    return v


def data_labels(text):
    """{label: bytes} for the .s file's labels that hold data (the first
    statement after one is a data directive), with .rept blocks expanded."""
    out = {}
    lines = [re.sub(r"[#;].*|/\*.*?\*/", "", ln).strip() for ln in text.splitlines()]
    labels = [(i, m.group(1)) for i, ln in enumerate(lines) for m in [re.match(r"^(\w+):$", ln)] if m]
    for k, (i, name) in enumerate(labels):
        end = labels[k + 1][0] if k + 1 < len(labels) else len(lines)
        body = [ln for ln in lines[i + 1:end] if ln and not re.match(r"^\.(balign|align|p2align)\b", ln)]
        if not body or body[0].split()[0] not in DATA and body[0].split()[0] not in STRINGS \
                and body[0].split()[0] not in SPACE and body[0].split()[0] != ".rept":
            continue
        stack = [[1, bytearray()]]
        for ln in body:
            op, _, args = ln.partition(" ")
            if op == ".rept":
                stack.append([int(args, 0), bytearray()])
            elif op == ".endr" and len(stack) > 1:
                n, b = stack.pop()
                stack[-1][1] += b * n
            elif op in DATA:
                size, fmt = DATA[op]
                for tok in args.split(","):
                    stack[-1][1] += struct.pack("<" + fmt, value(tok, fmt))
            elif op in STRINGS:
                s = re.match(r'^"(.*)"$', args.strip())
                raw = s.group(1).encode().decode("unicode_escape").encode("latin-1") if s else b""
                stack[-1][1] += raw + (b"\0" if STRINGS[op] else b"")
            elif op in SPACE:
                n, _, fill = args.partition(",")
                stack[-1][1] += bytes([value(fill, "B") if fill else 0]) * value(n, "I")
            elif re.match(r"^[a-z]", op):
                break  # an instruction: code from here on
        out[name] = bytes(stack[0][1])
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mod", required=True)
    ap.add_argument("--asm", default="source/**/*.s")
    ap.add_argument("--ported", action="append", default=[])
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    names = set()
    data = {}
    for p in glob.glob(os.path.join(a.mod, a.asm), recursive=True):
        text = open(p, encoding="utf-8", errors="replace").read()
        names |= set(re.findall(r"^\s*\.globa?l\s+(\w+)", text, re.M))
        data.update(data_labels(text))
    data = {n: b for n, b in data.items() if n in names}
    out = os.path.normcase(os.path.abspath(os.path.join(a.mod, a.out)))
    ported = set()
    for pat in a.ported:
        for p in glob.glob(os.path.join(a.mod, pat), recursive=True):
            if os.path.normcase(os.path.abspath(p)) == out:
                continue
            text = open(p, encoding="utf-8", errors="replace").read()
            ported |= {n for n in names if re.search(rf"\b{n}\s*\([^;{{]*\)\s*\{{", text)}
    stubs = sorted(names - ported - set(data))
    lines = ["// GENERATED by Paper Cut's tools/port/mod_asm_stubs.py. Do not edit.",
             "// The mod's assembly routines, which the PC doesn't run: what its code",
             "// patches branched to (the port skips those patches). One that runs logs.",
             "// Its assembly's data (tables its code reads) as the directives wrote it;",
             "// twice the room, for the PC's wider pointers if its code lays them out.",
             '#include "ttyd_mod/ttyd_mod.h"', "",
             'extern "C" const TtydModApi *ttyd_mod_api;', "",
             "static void portAsmStub(const char *name, bool &logged)", "{",
             "    if (!logged && ttyd_mod_api)", "    {",
             "        logged = true;",
             '        ttyd_mod_api->log("%s is GameCube assembly: it does nothing here", name);',
             "    }", "}", "", 'extern "C"', "{"]
    for n in stubs:
        lines += [f"    void {n}()", "    {", "        static bool logged = false;",
                  f'        portAsmStub("{n}", logged);', "    }"]
    for n in sorted(set(data) - ported):
        b = data[n]
        init = ", ".join(f"0x{x:02X}" for x in b) if any(b) else ""
        lines += [f"    alignas(8) unsigned char {n}[{max(2 * len(b), 8)}] = {{{init}}};"]
    lines += ["}", ""]
    text = "\n".join(lines)
    old = open(out, encoding="utf-8").read() if os.path.exists(out) else None
    if old != text:
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"{len(stubs)} assembly stubs, {len(data)} data labels ({len(ported)} ported by hand)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
