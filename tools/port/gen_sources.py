#!/usr/bin/env python3
"""Write port/sources_<version>.cmake from the object list in configure.py, so
the PC build compiles exactly the game/REL sources the matching build does for
that version (objects are gated per version by MatchingFor; JP-only files such
as seq_demo.c and the dig/qiz RELs are left out of the US list).

Usage: gen_sources.py [--version G8MJ01|G8ME01]   (default: every version)"""
import argparse, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

def read_configure():
    text = open(os.path.join(ROOT, "configure.py"), encoding="utf-8").read()
    return text[: text.index("if args.mode ==")]

def load_libs(text, version):
    argv = sys.argv
    sys.argv = ["configure.py", "--version", version]
    sys.path.insert(0, ROOT)
    g = {"__name__": "configure", "__file__": os.path.join(ROOT, "configure.py")}
    cwd = os.getcwd()
    os.chdir(ROOT)
    try:
        exec(compile(text, "configure.py", "exec"), g)
    finally:
        os.chdir(cwd)
        sys.argv = argv
    return g["VERSIONS"], g["config"].libs

def write_version(text, version):
    _, libs = load_libs(text, version)
    dol, rels = [], {}
    for lib in libs:
        src_dir = lib.get("src_dir", "src")
        if src_dir.startswith("libs/"):
            continue  # SDK / MusyX / runtime: replaced or built separately
        for obj in lib["objects"]:
            if not obj.completed:
                continue  # not part of this version
            path = f"{src_dir}/{obj.options.get('source') or obj.name}"
            if not path.endswith(".c") or not os.path.exists(os.path.join(ROOT, path)):
                continue
            if src_dir.startswith("rels/"):
                rels.setdefault(lib["lib"], []).append(path)
            else:
                dol.append(path)
    out = [f"# Generated by tools/port/gen_sources.py from configure.py ({version}). Do not edit.",
           "set(TTYD_DOL_SOURCES"]
    out += [f"    ${{CMAKE_SOURCE_DIR}}/{p}" for p in dol] + [")"]
    out.append(f"set(TTYD_RELS {' '.join(rels)})")
    for name, paths in rels.items():
        out.append(f"set(TTYD_REL_{name}_SOURCES")
        out += [f"    ${{CMAKE_SOURCE_DIR}}/{p}" for p in paths] + [")"]
    dest = os.path.join(ROOT, "port", f"sources_{version}.cmake")
    with open(dest, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{version}: dol {len(dol)} files, rels {len(rels)} ({sum(map(len, rels.values()))} files)")

def main():
    text = read_configure()
    versions, _ = load_libs(text, "G8MJ01")
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", choices=versions)
    args = ap.parse_args()
    for v in [args.version] if args.version else versions:
        write_version(text, v)

if __name__ == "__main__":
    main()
