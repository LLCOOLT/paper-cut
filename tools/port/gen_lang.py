#!/usr/bin/env python3
"""Generate port/settings/lang_tables.inc: the port's own menus in other
languages (port/settings/tr.cpp, port/include/port/tr.h), from
port/assets/lang/<code>.txt and the feature files in port/assets/lang/<code>/
(one per feature, so work on two features doesn't touch the same file).

Each file is UTF-8: an English line, then its translation on the next line,
then a blank line; lines starting with '#' are comments. A line break inside
a text is written \\n. The English is the text exactly as the code has it.

For each language the table holds, sorted by the English:
  - the translation in UTF-8 (the settings page, Dear ImGui);
  - the same in the game's encoding, for text drawn with the game's font (the
    Start menu's Settings tab): Latin-1 for the US and EU releases' font;
    NULL where that font can't show it (a letter outside its encoding).
    Japanese: ja_game.txt's text in Shift-JIS. The JP release's font has the
    kana and only about 200 other characters (JA_FONT below: no 、 or 。, few
    kanji), so its text is written for it, as the game's own is, and checked
    against them.
and the Japanese file's characters as Dear ImGui glyph ranges, so only those
are merged into the page's fonts.

The same format is read at run time from language packs (<user>/mods/<pack>/
lang/, docs/LANGUAGE_PACKS.md) by port/settings/tr.cpp's parseLang, with the
same rules; keep the two in step. The one difference: a pack's English line
with no translation under it is kept as not translated yet (the template's
empty lines), where this stops.

  gen_lang.py           write the table
  gen_lang.py --check   fail if it is out of date
"""
import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SRC = os.path.join(ROOT, "port", "assets", "lang")
OUT = os.path.join(ROOT, "port", "settings", "lang_tables.inc")
LANGS = ["de", "fr", "es", "it", "ja"]

# The JP release's font (f/papermarioset_JPN.bfn, its MAP1 blocks): ASCII but < > \ ` (a tag's marks), the
# kana, full-width digits and letters, and these
JA_FONT = set("=　．・：？！ー／～（）『』＋－×＆☆○→←↑↓♪８９わをんワヲンヴ位一引院右鵜雲駅王黄屋音下何家火花画回海界絵階"
              "外街学観間岩気技客丘休近空兄計月件見元原後光口港航行号合国黒今左財三山使姉子紙試事寺時自室実社車手樹出所助"
              "女勝小上城場色心森人図水数世星正生西青石赤説雪先船選前全組相草賊族村太体代大地中虫町長鳥直通弟天店伝島東当"
              "動道南二日入年買売箱鳩犯番飛姫氷負部風物分平宝方法砲北本魔妹味無娘名面木目問門夜用旅力列恋老話")
JA_FONT |= set(chr(c) for c in range(0x20, 0x7F) if chr(c) not in "<>\\`")
JA_FONT |= set(chr(c) for c in range(0x3041, 0x3094)) | set(chr(c) for c in range(0x30A1, 0x30F7))
JA_FONT |= set(chr(c) for c in range(0xFF10, 0xFF18)) | set(chr(c) for c in range(0xFF21, 0xFF3B))
JA_FONT |= {"\n"}  # a line break (written \n), not a letter: the game's messages break lines too


def read(code):
    """<code>.txt, then each feature's own file in <code>/ (port/assets/lang/de/<feature>.txt), by name"""
    pairs = {}
    paths = [os.path.join(SRC, code + ".txt")]
    extra = os.path.join(SRC, code)
    if os.path.isdir(extra):
        paths += [os.path.join(extra, f) for f in sorted(os.listdir(extra)) if f.endswith(".txt")]
    for path in paths:
        if not os.path.exists(path):
            continue
        name = os.path.relpath(path, SRC)
        lines = [l.rstrip("\r\n") for l in open(path, encoding="utf-8-sig")]
        lines = [l for l in lines if not l.startswith("#")]
        i = 0
        while i < len(lines):
            if lines[i] == "":
                i += 1
                continue
            if i + 1 >= len(lines) or lines[i + 1] == "":
                sys.exit(f"gen_lang: {name}: no translation for {lines[i]!r}")
            en, tr = lines[i].replace("\\n", "\n"), lines[i + 1].replace("\\n", "\n")
            if en in pairs and pairs[en] != tr:
                sys.exit(f"gen_lang: {name}: {en!r} translated twice")
            pairs[en] = tr
            i += 2
    return pairs


def c_string(data):
    """bytes as a C string literal (octal escapes: never run into the next character)"""
    out = '"'
    for b in data:
        c = chr(b)
        if c == '"' or c == "\\":
            out += "\\" + c
        elif c == "\n":
            out += "\\n"
        elif 0x20 <= b < 0x7F:
            out += c
        else:
            out += "\\%03o" % b
    return out + '"'


def game_bytes(code, text):
    try:
        return text.encode("cp932" if code == "ja" else "latin-1")
    except UnicodeEncodeError:
        return None


def ranges(chars):
    cps = sorted(set(ord(c) for c in chars if ord(c) > 0xFF))
    out = []
    for cp in cps:
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def generate():
    lines = ["// GENERATED by tools/port/gen_lang.py from port/assets/lang/*.txt. Do not edit.",
             "// {English, the translation (UTF-8), the same in the game's encoding or NULL}, sorted by the English.", ""]
    ja_chars = ""
    for code in LANGS:
        pairs = read(code)
        game_text = read("ja_game") if code == "ja" else {}
        for en, t in game_text.items():
            bad = "".join(sorted(set(c for c in t if c not in JA_FONT)))
            if bad:
                sys.exit(f"gen_lang: ja_game.txt: {en!r}: the JP font has no {bad}")
        lines.append(f"static const TrEntry kTr_{code}[] = {{")
        for en in sorted(pairs, key=lambda s: s.encode("utf-8")):
            tr = pairs[en]
            if code == "ja":
                # the JP font's text, or the page's when the font has all of it
                g = game_text.get(en, tr)
                game = g.encode("cp932") if all(c in JA_FONT for c in g) else None
            else:
                game = game_bytes(code, tr)
            lines.append("    {%s, %s, %s}," % (c_string(en.encode("utf-8")), c_string(tr.encode("utf-8")),
                                                c_string(game) if game is not None else "nullptr"))
            if code == "ja":
                ja_chars += tr
        if not pairs:
            lines.append("    {nullptr, nullptr, nullptr},")
        lines.append("};")
        lines.append(f"static const size_t kTrCount_{code} = {len(pairs)};")
        lines.append("")
    lines.append("// the Japanese translations' characters (and the kana and punctuation around them), for the fonts")
    lines.append("static const ImWchar kTrJaGlyphs[] = {")
    rs = ranges(ja_chars + "日本語" + "".join(chr(c) for c in range(0x3000, 0x3100)) + "".join(chr(c) for c in range(0xFF00, 0xFF70)))
    for a, b in rs:
        lines.append(f"    0x{a:04X}, 0x{b:04X},")
    lines.append("    0,")
    lines.append("};")
    lines.append("")
    lines.append("// the JP release's font past ASCII (JA_FONT): {character, its Shift-JIS}, by character (language packs)")
    lines.append("static const TrJaFontChar kTrJaFontMap[] = {")
    for c in sorted(JA_FONT, key=ord):
        if ord(c) >= 0x80:
            b = c.encode("cp932")
            lines.append(f"    {{0x{ord(c):04X}, 0x{int.from_bytes(b, 'big'):04X}}},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = generate()
    if a.check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            sys.exit("gen_lang: port/settings/lang_tables.inc is out of date: run tools/port/gen_lang.py")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"gen_lang: wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
