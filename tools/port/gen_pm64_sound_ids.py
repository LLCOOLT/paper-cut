#!/usr/bin/env python3
"""Writes port/include/port/pm64_sound_ids.h: Paper Mario 64's sound effect names and ids, as the PM64 decomp
(pmret/papermario) names them in include/enums.h (enum SoundIDs), for Paper Cut's PM64 sound effect player
(port/include/port/pm64_sfx.h). Only names and numbers: nothing of the ROM.

The raw ids are kept (0x0001..0x03FF and the extra section's 0x2000 | n). The looping ids (SOUND_LOOP_*,
0x8000xxxx) go to their raw script (SOUND_LRAW_* of the same name), which loops by itself until stopped; the door
and alternating ids (table indices in the N64 engine) are left out.

usage: gen_pm64_sound_ids.py <pm64 decomp>/include/enums.h [out.h]
"""
import re
import sys

def main():
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "port/include/port/pm64_sound_ids.h"
    text = open(src, encoding="utf-8").read()
    m = re.search(r"enum SoundIDs \{(.*?)\n\};", text, re.S)
    if not m:
        sys.exit("enum SoundIDs not found")
    raw, loops = {}, []
    for name, unk, val in re.findall(r"^\s+(SOUN[CD]_\w+)\s*=\s*(SOUND_ID_UNK \| )?(0x[0-9A-Fa-f]+)", m.group(1), re.M):
        v = int(val, 16) | (0x2000 if unk else 0)
        if name == "SOUNC_CHECK_MAILBOX":  # the decomp's typo
            name = "SOUND_CHECK_MAILBOX"
        if v & 0x80000000:
            if (v >> 28) == 8:
                loops.append(name)
            continue
        if v == 0 or v > 0x23FF:
            continue
        raw[name] = v
    for name in loops:
        lraw = "SOUND_LRAW_" + name[len("SOUND_LOOP_"):]
        if lraw in raw:
            raw[name] = raw[lraw]
    rows = sorted(raw.items())  # sorted by name: portPm64SfxId's binary search
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/port/gen_pm64_sound_ids.py from the PM64 decomp's include/enums.h. Do not edit.\n")
        f.write("// Paper Mario 64's sound effects by name (port/include/port/pm64_sfx.h): PM64_SOUND(NAME, id), the\n")
        f.write("// decomp's SOUND_ name without its prefix, sorted by name. SOUND_LOOP_* are their SOUND_LRAW_* script.\n")
        f.write("#ifndef PORT_PM64_SOUND_IDS_H\n#define PORT_PM64_SOUND_IDS_H\n\n")
        f.write("#define PM64_SOUND_LIST(PM64_SOUND) \\\n")
        for name, v in rows:
            f.write("    PM64_SOUND(%s, 0x%04X) \\\n" % (name[len("SOUND_"):], v))
        f.write("\n")
        f.write("/* PM64_SOUND_GOOMBARIO_HEADBONK etc.: the ids as constants */\n")
        f.write("enum {\n#define PM64_SOUND_ENUM(n, v) PM64_SOUND_##n = v,\n    PM64_SOUND_LIST(PM64_SOUND_ENUM)\n#undef PM64_SOUND_ENUM\n};\n\n")
        f.write("#endif\n")
    print("gen_pm64_sound_ids: %d names -> %s" % (len(rows), out))

if __name__ == "__main__":
    main()
