#!/usr/bin/env python3
"""Generate port/mods/evt_table_gen.h: what a mod's text scripts are made of
(docs/MODDING.md, "Scripts"), for the assembler in port/mods/evt_asm.cpp.

- Commands: each script macro of the decomp's include/evt/evt_cmd.h
  (`#define LOOP(n) EVT_CMD(1, OPCODE_DO), n,`): its name, opcode and
  argument count, so a mod's script is written as the game's own are and a
  script from the decomp's sources reads the same. Also each opcode by its
  own name (OPCODE_SET as SET), with any number of arguments.
- Constants: the game headers' enum constants and numeric #defines
  (ITEM_MUSHROOM, ...), each evaluated by clang (the US Aurora build's
  flags), names sorted for a binary search.

  gen_evt_table.py [--check]
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_game_all

ROOT = gen_game_all.ROOT
OUT = os.path.join(ROOT, "port", "mods", "evt_table_gen.h")
CMD_H = os.path.join(ROOT, "include", "evt", "evt_cmd.h")
MGR_H = os.path.join(ROOT, "include", "manager", "evtmgr.h")
ENUM_CONST = re.compile(r"EnumConstantDecl 0x[0-9a-f]+ .*? (\w+) '[^']*'")
VALUE = re.compile(r"value: Int (-?\d+)")


def opcodes():
    text = open(MGR_H, encoding="utf-8").read()
    return {m.group(1): int(m.group(2), 0) for m in re.finditer(r"\bOPCODE_(\w+)\s*=\s*(\w+)", text)}


def commands(ops):
    """[(name, opcode, argument count or -1 for any)]: the macros, then the
    opcodes' own names where no macro has that name."""
    text = open(CMD_H, encoding="utf-8").read().replace("\\\n", " ")
    out = {}
    for m in re.finditer(r"^#define (\w+)(\(([^)]*)\))?\s+EVT_CMD\(([^,]+),\s*OPCODE_(\w+)\)", text, re.M):
        name, count, op = m.group(1), m.group(4).strip(), m.group(5)
        if op in ops:
            out[name] = (ops[op], int(count) if count.isdigit() else -1)  # CALL(...): any number
    out.setdefault("RETURN", (ops["END_EVENT"], 0))
    for op, value in ops.items():
        out.setdefault(op, (value, -1))
    return sorted((name, op, n) for name, (op, n) in out.items())


def constants(fl):
    """{name: value}: the game headers' enum constants and the #defines
    clang can evaluate as a constant expression."""
    with tempfile.TemporaryDirectory() as tmp:
        text = open(gen_game_all.OUT, encoding="utf-8").read()
        p = os.path.join(tmp, "consts.cpp")
        with open(p, "w") as f:
            f.write(text)
        cxx = os.environ.get("CLANGXX", "clang++")
        flags = ["-x", "c++", "-std=gnu++20", "-w", *fl]
        ast = subprocess.run([cxx, "-fsyntax-only", "-Xclang", "-ast-dump", "-fno-color-diagnostics", *flags, p],
                             cwd=ROOT, capture_output=True, text=True, errors="replace").stdout
        names = {m.group(1) for m in ENUM_CONST.finditer(ast)}
        macros = subprocess.run([cxx, "-E", "-dM", *flags, p], cwd=ROOT, capture_output=True, text=True,
                                errors="replace").stdout
        names |= {m.group(1) for m in re.finditer(r"^#define ([A-Z][A-Z0-9_]+) (.+)$", macros, re.M)
                  if re.search(r"\d", m.group(2)) and '"' not in m.group(2)}
        names = sorted(names)
        out = {}
        probe = os.path.join(tmp, "eval.cpp")
        for i in range(0, len(names), 2000):
            chunk = names[i:i + 2000]
            with open(probe, "w") as f:
                f.write(text + "\n")
                for n in chunk:
                    f.write(f"constexpr long long ttyd_const_{n} = (long long)({n});\n")
            r = subprocess.run([cxx, "-fsyntax-only", "-ferror-limit=0", "-Xclang", "-ast-dump",
                                "-fno-color-diagnostics", *flags, probe],
                               cwd=ROOT, capture_output=True, text=True, errors="replace")
            bad = set(re.findall(r"ttyd_const_(\w+)", r.stderr))
            cur = None
            for ln in r.stdout.splitlines():
                m = re.search(r"VarDecl 0x[0-9a-f]+ .*? ttyd_const_(\w+) ", ln)
                if m:
                    cur = m.group(1)
                    continue
                m = VALUE.search(ln)
                if m and cur:
                    if cur not in bad:
                        out[cur] = int(m.group(1))
                    cur = None
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    ops = opcodes()
    cmds = commands(ops)
    consts = constants(gen_game_all.flags())
    lines = ["/* GENERATED by tools/port/gen_evt_table.py. Do not edit.",
             " * Script commands (the decomp's include/evt/evt_cmd.h macros and the",
             " * opcodes' names) and the game headers' constants, for port/mods/evt_asm.cpp. */",
             "#pragma once", "", "struct PortEvtCommand {", "    const char* name;", "    int opcode;",
             "    int args; /* -1: any number */", "};", "",
             "static const PortEvtCommand kPortEvtCommands[] = {"]
    lines += [f'    {{"{n}", {op}, {c}}},' for n, op, c in cmds]
    lines += ["};", "", "struct PortEvtConstant {", "    const char* name;", "    long long value;", "};", "",
              "static const PortEvtConstant kPortEvtConstants[] = {"]
    # (the most negative long long has no literal: -9223372036854775808 is -(2^63))
    lines += [f'    {{"{n}", {v}LL}},' if v != -(1 << 63) else f'    {{"{n}", -9223372036854775807LL - 1}},'
              for n, v in sorted(consts.items())]
    lines += ["};", ""]
    text = "\n".join(lines)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    what = f"{len(cmds)} commands, {len(consts)} constants"
    if a.check:
        print(f"{'ok   ' if old == text else 'STALE'} {os.path.relpath(OUT, ROOT)} ({what})")
        return 0 if old == text else 1
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"{os.path.relpath(OUT, ROOT)}: {what}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
