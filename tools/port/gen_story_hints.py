#!/usr/bin/env python3
"""Generate port/src/aurora/story_hints.inc: for each step of the story
(include/evt/evt_story.h, GSW 0), its value, the area its scene is in (the
first map named in its comment that isn't a chapter card, sys_*) and its
name. The Journal's "where next?" hint (port/src/aurora/journal_hint_aurora.c)
shows the area of the first step past the story's value now.

  gen_story_hints.py           write the table
  gen_story_hints.py --check   fail if it is out of date
"""
import argparse
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SRC = os.path.join(ROOT, "include", "evt", "evt_story.h")
OUT = os.path.join(ROOT, "port", "src", "aurora", "story_hints.inc")
LINE = re.compile(r"^\s*STORY_\w+\s*=\s*(-?\d+),\s*//\s*(.*)$")


def generate():
    rows = []
    for line in open(SRC, encoding="utf-8"):
        m = LINE.match(line)
        if not m:
            continue
        value, comment = int(m.group(1)), m.group(2)
        names = re.findall(r'"([^"]*)"', comment)
        maps = [x for x in re.findall(r"\((\w{3})_\w+\)", comment) if x != "sys"]
        if not names or not maps:
            continue
        rows.append((value, maps[0], names[0]))
    rows.sort()
    out = ["// GENERATED by tools/port/gen_story_hints.py from include/evt/evt_story.h. Do not edit.",
           "// {the story's value (GSW 0), the area (its maps' prefix), the step's name}, in story order.", ""]
    out.append("static const StoryStep kStorySteps[] = {")
    for value, area, name in rows:
        out.append('    {%d, "%s", "%s"},' % (value, area, name.replace("\\", "\\\\").replace('"', '\\"')))
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = generate()
    if a.check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            sys.exit("gen_story_hints: port/src/aurora/story_hints.inc is out of date: run tools/port/gen_story_hints.py")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"gen_story_hints: wrote {os.path.relpath(OUT, ROOT)} ({text.count(chr(10)) - 4} steps)")


if __name__ == "__main__":
    main()
