#!/usr/bin/env python3
"""Writes port/src/common/recipe_hints.inc from rels/gor/src/gor_01.c: Zess T.'s
recipe tables (one ingredient, and the two-ingredient cookbook, the US/EU
table and the JP one) as {dish, ingredient, ingredient} by the items' internal
ids (itemDataTable[].id), for the recipe book's hints (port/src/common/qol_pc.c).

    python tools/port/gen_recipe_hints.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "rels" / "gor" / "src" / "gor_01.c"
OUT = ROOT / "port" / "src" / "common" / "recipe_hints.inc"

ROW = re.compile(r'^\s*\{"([^"]*)", "([^"]*)", "([^"]*)"\},\s*$')


def block(lines, start):
    """The rows of the table that opens at or after line start, and the line after it."""
    i = start
    while not lines[i].rstrip().endswith("[] = {"):
        i += 1
    rows = []
    i += 1
    while not lines[i].startswith("};"):
        m = ROW.match(lines[i])
        if m:
            rows.append(m.groups())
        i += 1
    return rows, i + 1


def main():
    lines = SRC.read_text(encoding="utf-8").splitlines()
    simple_at = next(i for i, l in enumerate(lines) if l.startswith("SimpleRecipe R_simple_recipe_table[] = {"))
    simple, _ = block(lines, simple_at)
    us_at = next(i for i, l in enumerate(lines) if l.startswith("CookRecipe R_cookbook_recipe_table[] = {"))
    us, after = block(lines, us_at)
    jp, _ = block(lines, after)

    def emit(rows, two):
        out = []
        for r in rows:
            if two:
                a, b, dish = r
            else:
                a, dish, dish2 = r
                dish = dish2 or dish  # (after the cookbook: what she makes from it then)
                b = ""
            if dish:
                out.append('    {"%s", "%s", "%s"}, /* %s, %s, %s */'
                           % (sjis(dish), sjis(a), sjis(b), dish, a, b or "-"))
        return out

    def sjis(s):
        # the game's ids are Shift-JIS at run time (tools/port/sjis_src.py rewrites the game's sources' literals;
        # this file is included from port code, which it doesn't touch): octal escapes of the cp932 bytes
        return "".join(c if ord(c) < 0x80 else "".join("\\%03o" % x for x in c.encode("cp932")) for c in s)

    text = [
        "// GENERATED by tools/port/gen_recipe_hints.py from rels/gor/src/gor_01.c. Do not edit.",
        "// Zess T.'s recipes as {dish, ingredient, second ingredient or \"\"}, by itemDataTable[].id:",
        "// the one-ingredient table, then the cookbook (US and EU's, or JP's). The ids are Shift-JIS, as the",
        "// game's own are at run time (each row's comment has them as text).",
        "",
        "static const RecipeHint kRecipeHints[] = {",
    ]
    text += emit(simple, False)
    text.append("#if VERSION >= VERSION_US")
    text += emit(us, True)
    text.append("#else")
    text += emit(jp, True)
    text.append("#endif")
    text.append("};")
    OUT.write_text("\n".join(text) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(simple)} + {len(us)} / {len(jp)} recipes")


if __name__ == "__main__":
    main()
