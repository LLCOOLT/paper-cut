"""port/src/common/online_roots.inc: the root certificates online co-op's relay
(Cloudflare, on workers.dev) chains to, from curl's copy of Mozilla's list.
  gen_online_roots.py cacert.pem     (https://curl.se/ca/cacert.pem)
Cloudflare's certificates come from Google Trust Services, Let's Encrypt and
SSL.com: their roots, nothing else."""
import os
import sys

ROOTS = [
    "GTS Root R1", "GTS Root R3", "GTS Root R4",
    "ISRG Root X1", "ISRG Root X2",
    "SSL.com Root Certification Authority ECC", "SSL.com Root Certification Authority RSA",
    "SSL.com TLS ECC Root CA 2022", "SSL.com TLS RSA Root CA 2022",
]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "port", "src", "common",
                   "online_roots.inc")


def main():
    lines = open(sys.argv[1], encoding="utf-8").read().splitlines()
    dated = next((l for l in lines if l.startswith("## Certificate data from Mozilla")), "")
    found = {}
    for i, line in enumerate(lines):
        if line in ROOTS:
            begin = lines.index("-----BEGIN CERTIFICATE-----", i)
            end = lines.index("-----END CERTIFICATE-----", begin)
            found[line] = lines[begin:end + 1]
    missing = [r for r in ROOTS if r not in found]
    if missing:
        sys.exit("not in the list: " + ", ".join(missing))
    out = ["/* GENERATED by tools/port/gen_online_roots.py. Do not edit.",
           " * The relay's root certificates (PEM, one string), from curl's copy of",
           " * Mozilla's list" + (" (" + dated.split("as of:")[-1].strip() + ")" if dated else "") + ". */",
           "static const char kOnlineRoots[] ="]
    for name in ROOTS:
        out.append(f"    /* {name} */")
        out += [f'    "{l}\\n"' for l in found[name]]
    out[-1] += ";"
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(OUT), len(ROOTS), "roots")


if __name__ == "__main__":
    main()
