#!/usr/bin/env python3
"""The decomp's names for the story progress values (GSW 0), the saved words
(GSW) and the saved flags (GSWF) from include/evt/evt_story.h, as tables for
the practice tools' flag viewer and the speedrun splits
(port/src/common/story_names_gen.c, read through port/include/port/practice.h).

    python tools/port/gen_story_names.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER = os.path.join(ROOT, "include", "evt", "evt_story.h")
OUT = os.path.join(ROOT, "port", "src", "common", "story_names_gen.c")

ENTRY = re.compile(r"^\s*([A-Z][A-Z0-9_]*)\s*=\s*(\d+),?\s*(?://\s*(.*))?$")


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_enums():
    enums = {}
    current = None
    above = []  # the comment lines over the next entry
    for line in open(HEADER, encoding="utf-8"):
        m = re.match(r"^typedef enum (\w+)", line)
        if m:
            current = m.group(1)
            enums[current] = []
            continue
        if current and line.startswith("}"):
            current = None
            continue
        if current:
            c = re.match(r"^\s*//\s?(.*)$", line)
            if c:
                above.append(c.group(1).strip())
                continue
            m = ENTRY.match(line)
            if m:
                name, value, comment = m.group(1), int(m.group(2)), (m.group(3) or "").strip()
                if not comment:
                    comment = " ".join(above)
                if current == "StoryProgress":
                    # the story rows' English event name: the comment's first quoted text
                    q = re.search(r'"([^"]*)"', comment)
                    comment = q.group(1).strip() if q else ""
                enums[current].append((value, name, comment))
            above = []
    return enums


def main():
    enums = read_enums()
    tables = [("StoryProgress", "portStoryNames"), ("GswId", "portGswNames"), ("GswfId", "portGswfNames")]
    out = ["/* GENERATED by tools/port/gen_story_names.py from include/evt/evt_story.h. Do not edit. */",
           '#include "port/practice.h"', ""]
    for enum, table in tables:
        rows = sorted(enums[enum], key=lambda r: r[0])
        out.append("const PortNamedValue %s[] = {" % table)
        for value, name, label in rows:
            out.append("    {%d, %s, %s}," % (value, c_string(name), c_string(label)))
        out.append("};")
        out.append("const int %sCount = %d;" % (table, len(rows)))
        out.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote %s" % os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
