#!/usr/bin/env python3
"""Generate port/src/aurora/quiz_shops.inc: what the game's item shops sell
and pay, for the quiz party's shop questions (port/src/aurora/quiz_aurora.c),
from the decomp's shop maps (rels/*/src/*.c, the arrays they hand
evt_shop_setup):

  - kQuizShopGoods: every ShopItem array (a shelf's item and its price in
    coins), so "which costs the most in a shop" offers only items a shop
    sells, at the prices it sells them for;
  - kQuizShopTrades: every ShopDb array (a shop's own price for an item Mario
    sells it, in place of the item table's sell price), so "what does a shop
    give for" asks only about items every shop pays the same for.

#if blocks are read as the US release builds them (VERSION_US, as
gen_tattle_cards.py does); the retail releases' lists are the same.

  gen_quiz_shops.py           write the table
  gen_quiz_shops.py --check   fail if it is out of date
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_tattle_cards import us_lines  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "port", "src", "aurora", "quiz_shops.inc")


def arrays(text, kind):
    """(name, [(item, number)]) for each `kind name[] = {...};` in the text"""
    for m in re.finditer(r"\b" + kind + r"\s+(\w+)\[\]\s*=\s*\{(.*?)\n\};", text, re.S):
        rows = re.findall(r"\{\s*(ITEM_\w+)\s*,\s*(-?\d+)", m.group(2))
        if rows:
            yield m.group(1), [(i, int(p)) for i, p in rows]


def main():
    goods, trades = [], []
    for area in sorted(os.listdir(os.path.join(ROOT, "rels"))):
        d = os.path.join(ROOT, "rels", area, "src")
        if area in ("tst", "jon") or not os.path.isdir(d):  # the test rooms; the Pit has no item shop
            continue
        for f in sorted(os.listdir(d)):
            if not f.endswith(".c"):
                continue
            raw = open(os.path.join(d, f), encoding="utf-8", errors="replace").read()
            if "evt_shop_setup" not in raw:
                continue
            text = us_lines(raw)
            where = "%s/%s" % (area, f[:-2])
            for name, rows in arrays(text, "ShopItem"):
                goods += [(i, p, where, name) for i, p in rows]
            for name, rows in arrays(text, "ShopDb"):
                trades += [(i, p, where, name) for i, p in rows]
    lines = [
        "/* Generated by tools/port/gen_quiz_shops.py from the decomp's shop maps: do not edit. */",
        "/* What the item shops sell (item, price in coins) and pay for what Mario sells them (item,",
        " * coins: in place of the item table's sell price), for the quiz party's shop questions. */",
        "static const struct {",
        "    short item, coins;",
        "} kQuizShopGoods[] = {",
    ]
    lines += ["    {%s, %d}, /* %s %s */" % (i, p, w, n) for i, p, w, n in goods]
    lines += ["}, kQuizShopTrades[] = {"]
    lines += ["    {%s, %d}, /* %s %s */" % (i, p, w, n) for i, p, w, n in trades]
    lines += ["};", ""]
    text = "\n".join(lines)
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read().replace("\r\n", "\n") if os.path.exists(OUT) else ""
        if old != text:
            print("quiz_shops.inc is out of date: run tools/port/gen_quiz_shops.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("%d goods, %d trades" % (len(goods), len(trades)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
