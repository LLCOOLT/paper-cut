#!/usr/bin/env python3
"""Generate port/archipelago/ttyd_ap_data.h: the data the port's Archipelago
support for TTYD needs from the TTYD apworld (github.com/jamesbrq/
ArchipelagoTTYD, MIT), for its version (US):

- items: Archipelago id -> the game's item id (rom_id), and its class;
- locations: id, the flag that marks it checked (GSW or GSWF, from the
  client's location_gsw_info), whether it is a shop's (with a price) or a
  tattle's (with its units), and where its item is in the game: each of the
  apworld's patch offsets (main.dol or a REL), translated to the PC build's
  data by tools/port/gc_offsets.py (a script's word, a table's field, or the
  GameCube low memory the mod keeps its tables in).

  gen_ttyd_ap.py --apworld ../ArchipelagoTTYD [--version G8ME01] [--check]

The apworld is read, not run: its JSON and, through Python's ast, the
literal tables of Data.py.
"""
import argparse
import ast
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gc_offsets

ROOT = gc_offsets.ROOT
OUT = os.path.join(ROOT, "port", "archipelago", "ttyd_ap_data.h")
KIND = {"script": "TTYD_AP_SCRIPT", "data": "TTYD_AP_DATA", "lowmem": "TTYD_AP_LOWMEM"}


def data_tables(path):
    """Data.py's literal tables by name (GSWType.GSW and .GSWF as 0 and 1)."""
    tree = ast.parse(open(path, encoding="utf-8").read())

    class Enums(ast.NodeTransformer):
        def visit_Attribute(self, node):
            if isinstance(node.value, ast.Name) and node.value.id == "GSWType":
                return ast.copy_location(ast.Constant({"GSW": 0, "GSWF": 1}[node.attr]), node)
            return node

    out = {}
    for node in tree.body:
        targets = node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
        value = getattr(node, "value", None)
        for t in targets:
            if isinstance(t, ast.Name) and value is not None:
                try:
                    out[t.id] = ast.literal_eval(Enums().visit(value))
                except (ValueError, SyntaxError, TypeError):
                    pass
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--apworld", required=True, help="a checkout or extracted .apworld of ArchipelagoTTYD")
    ap.add_argument("--version", default="G8ME01")
    ap.add_argument("--disc", default=None)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    disc = a.disc or os.path.join(ROOT, "orig", a.version)
    items = json.load(open(os.path.join(a.apworld, "json", "items.json"), encoding="utf-8"))
    locations = json.load(open(os.path.join(a.apworld, "json", "locations.json"), encoding="utf-8"))
    tables = data_tables(os.path.join(a.apworld, "Data.py"))
    gsw = tables["location_gsw_info"]
    shops = set(tables["shop_items"])
    units = tables["location_to_unit"]
    rom_of = {i["id"]: i["rom_id"] for i in items}

    lines = ["/* GENERATED by tools/port/gen_ttyd_ap.py from the TTYD apworld",
             " * (github.com/jamesbrq/ArchipelagoTTYD, MIT License, Copyright (c) 2025",
             " * jamesbrq). Do not edit. Its items, locations and the flags that check",
             " * them, and where each location's item is in the PC build (gc_offsets.py). */",
             "#pragma once", "", '#include "ttyd_ap.h"', "",
             "static const TtydApItem kTtydApItems[] = {"]
    cls = {"progression": 1, "useful": 2, "trap": 4, "filler": 0, "progression_skip_balancing": 1}
    for it in sorted(items, key=lambda i: i["id"]):
        lines.append(f'    {{{it["id"]}, {it["rom_id"]}, {cls.get(it.get("progression"), 0)}}}, // {it["item_name"]}')
    lines += ["};", "", "static const TtydApTarget kTtydApTargets[] = {"]
    loc_lines, failures, count = [], [], 0
    for loc in sorted(locations, key=lambda l: l["id"]):
        first = count
        rel = loc.get("rel")
        for i, off in enumerate(loc.get("offsets", [])):
            off = int(off, 16)
            # the patcher writes "30 Coins"'s second offset in pik's REL
            file = "main.dol" if rel == "dol" else f"rel/{'pik' if '30 Coins' in loc['name'] and i == 1 else rel}.rel"
            for what, at in (("item", off), ("price", off + 4)) if loc["id"] in shops else (("item", off),):
                try:
                    t = gc_offsets.translate(a.version, disc, file, at)
                except gc_offsets.Error as e:
                    failures.append(f"{loc['name']} {file}:0x{at:X}: {e}")
                    continue
                if t["kind"] == "code":
                    failures.append(f"{loc['name']} {file}:0x{at:X}: code ({t['name']}), by hand")
                    continue
                width = 2 if rel == "dol" else 4
                area = "" if rel == "dol" else file[4:-4]
                lines.append(f'    {{"{t["name"]}", "{area}", 0x{t["pc_offset"]:X}, {KIND[t["kind"]]}, {width}, '
                             f'{1 if what == "price" else 0}, 0x{at:X}}},')
                count += 1
        g = gsw.get(loc["id"], (0, 0, 0))
        flags = ("TTYD_AP_SHOP | " if loc["id"] in shops else "") + \
                ("TTYD_AP_TATTLE | " if loc["id"] in units else "") + "0"
        name = loc["name"].replace("\\", "\\\\").replace('"', '\\"')
        vanilla = rom_of.get(loc.get("vanilla_item"), 0)
        loc_lines.append(f'    {{{loc["id"]}, "{name}", {g[0]}, {g[1]}, {g[2]}, {flags}, {first}, {count - first}, '
                         f'{vanilla}}},')
    # locations the client checks that have no item to place (tattles: the
    # mod's own table, by unit)
    for lid in sorted(set(gsw) - {l["id"] for l in locations}):
        g = gsw[lid]
        flags = "TTYD_AP_TATTLE | 0" if lid in units else "0"
        loc_lines.append(f'    {{{lid}, "", {g[0]}, {g[1]}, {g[2]}, {flags}, {count}, 0, 0}},')
    lines += ["};", "", "static const TtydApLocation kTtydApLocations[] = {"] + loc_lines + ["};", ""]
    lines += ["/* tattle locations: their units (the patcher's 0xB00 + 2 * (unit - 1) table) */",
              "static const TtydApTattle kTtydApTattles[] = {"]
    for lid, us in sorted(units.items()):
        for u in us:
            lines.append(f"    {{{lid}, {u}}},")
    lines += ["};", ""]
    text = "\n".join(lines)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    what = f"{len(items)} items, {len(loc_lines)} locations, {count} targets, {len(failures)} by hand"
    for f in failures:
        print("  by hand:", f)
    if a.check:
        print(f"{'ok   ' if old == text else 'STALE'} {os.path.relpath(OUT, ROOT)} ({what})")
        return 0 if old == text else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"{os.path.relpath(OUT, ROOT)}: {what}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
