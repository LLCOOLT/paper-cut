#!/usr/bin/env python3
"""Generate port/src/sdk/stubs_generated.c: a logging no-op for every SDK /
MusyX function the game links against that the port does not implement yet.
Each stub prints "STUB <name>" on first call and returns 0. The number of
stubs is the platform-layer work list; delete a name here by implementing it.

usage: ninja -C build-pc ttyd 2>&1 | tools/port/gen_stubs.py
       (reads linker output on stdin)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER_DIRS = ["libs/dolsdk2004/include", "libs/musyx/include"]
SDK = re.compile(r"^_*(GX|GD|OS|DC|IC|LC|DVD|AR|ARQ|AI|AX|DSP|CARD|VI|PAD|SI|EXI|DEMO|THP|"
                 r"PS|C_|MTX|VEC|snd|synth|hw|sal|s3d|aram)[A-Za-z0-9_]*$")
OUT = os.path.join(ROOT, "port", "src", "headless", "sdk", "stubs_generated.c")

def prototypes():
    protos = {}
    for d in HEADER_DIRS:
        for dp, _, fns in os.walk(os.path.join(ROOT, d)):
            for fn in fns:
                if not fn.endswith(".h"):
                    continue
                text = open(os.path.join(dp, fn), errors="replace").read()
                text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
                for m in re.finditer(r"^[ \t]*((?:extern\s+)?(?:const\s+)?[A-Za-z_][\w\s\*]*?[\s\*])"
                                     r"([A-Za-z_]\w*)\s*\(([^;{}]*?)\)\s*;", text, re.M):
                    ret, name, args = m.group(1).replace("extern", "").strip(), m.group(2), m.group(3)
                    if "typedef" in ret or "#" in ret:
                        continue
                    protos.setdefault(name, (ret, " ".join(args.split()), os.path.relpath(os.path.join(dp, fn), ROOT)))
    return protos

def main():
    missing = sorted(set(re.findall(r"undefined reference to [`']([A-Za-z_]\w*)'", sys.stdin.read())))
    protos = prototypes()
    existing = set()
    if os.path.exists(OUT):
        existing = set(re.findall(r"^\s+STUB_BEGIN\((\w+)\);", open(OUT).read(), re.M))
    implemented = set()
    # The port's shims and the MusyX sources the PC build links (libs/musyx, PC target).
    impl_dirs = [os.path.join(ROOT, "port", "src"), os.path.join(ROOT, "libs", "musyx", "src")]
    for dp, _, fns in (w for d in impl_dirs for w in os.walk(d)):
        if os.sep + "aurora" in dp:
            continue  # the stubs are for the headless backend
        for fn in fns:
            if fn.endswith(".c") and fn != os.path.basename(OUT):
                text = open(os.path.join(dp, fn), errors="replace").read()
                implemented |= set(re.findall(r"^[A-Za-z_][\w \*]*?\b(\w+)\s*\([^;]*?\)\s*\{", text, re.M))
    names = sorted((set(n for n in missing if SDK.match(n)) | existing) - implemented)
    lines = ["/* Generated by tools/port/gen_stubs.py; regenerate, don't edit.",
             " * Logging no-ops for SDK functions the port does not implement yet. */",
             "#include <dolphin.h>", "#include <dolphin/gx.h>", "#include <dolphin/card.h>",
             "#include <dolphin/ai.h>", "#include <musyx/musyx.h>", "#include <stdio.h>", "",
             "#define STUB_BEGIN(name) \\",
             "    static int name##_logged; \\",
             "    if (!name##_logged) { name##_logged = 1; fprintf(stderr, \"STUB \" #name \"\\n\"); }",
             ""]
    unknown = []
    for n in names:
        if n not in protos:
            unknown.append(n)
            continue
        ret, args, src = protos[n]
        params = args if args else "void"
        body = f"    STUB_BEGIN({n});"
        if ret != "void":
            body += f"\n    return ({ret})0;"
        lines.append(f"/* {src} */\n{ret} {n}({params}) {{\n{body}\n}}\n")
    open(OUT, "w").write("\n".join(lines).replace("\nSTUB_BEGIN", "\nSTUB_BEGIN"))
    print(f"{len(names) - len(unknown)} stubs written; {len(unknown)} SDK names without a prototype:"
          f" {' '.join(unknown)}")

if __name__ == "__main__":
    main()
