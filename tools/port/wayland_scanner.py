#!/usr/bin/env python3
"""wayland-scanner's client side, for cross-compiling SDL3's Wayland driver on
a host that has no wayland-scanner (Windows): the ARM64 handheld build
(cmake/toolchains/linux-arm64.cmake), for ROCKNIX's Sway sessions.

  wayland_scanner.py --version
  wayland_scanner.py client-header|private-code|public-code INPUT.xml OUTPUT

Writes what wayland-scanner 1.18 writes (the wl_proxy_marshal calls every
libwayland-client from 1.18 on has), from the protocol's XML.
"""
import sys
import xml.etree.ElementTree as ET

VERSION = "1.18.0"


class Arg:
    def __init__(self, e):
        self.name = e.get("name")
        self.type = e.get("type")
        self.interface = e.get("interface")
        self.nullable = e.get("allow-null") == "true"
        self.enum = e.get("enum")


class Message:
    def __init__(self, e, opcode):
        self.name = e.get("name")
        self.since = int(e.get("since", "1"))
        self.destructor = e.get("type") == "destructor"
        self.args = [Arg(a) for a in e.findall("arg")]
        self.opcode = opcode
        self.new_id = next((a for a in self.args if a.type == "new_id"), None)
        self.all_null = all(not (a.type in ("object", "new_id") and a.interface) for a in self.args)
        self.type_index = 0

    def signature(self):
        s = str(self.since) if self.since > 1 else ""
        for a in self.args:
            if a.nullable:
                s += "?"
            if a.type == "new_id" and not a.interface:
                s += "su"
            s += {"int": "i", "uint": "u", "fixed": "f", "string": "s", "object": "o", "new_id": "n",
                  "array": "a", "fd": "h"}[a.type]
        return s

    def type_count(self):
        return sum(3 if a.type == "new_id" and not a.interface else 1 for a in self.args)


class Interface:
    def __init__(self, e):
        self.name = e.get("name")
        self.version = int(e.get("version", "1"))
        self.requests = [Message(m, i) for i, m in enumerate(e.findall("request"))]
        self.events = [Message(m, i) for i, m in enumerate(e.findall("event"))]
        self.enums = []
        for en in e.findall("enum"):
            entries = [(x.get("name"), x.get("value"), int(x.get("since", "1"))) for x in en.findall("entry")]
            self.enums.append((en.get("name"), entries))


def parse(path):
    root = ET.parse(path).getroot()
    return root.get("name"), [Interface(i) for i in root.findall("interface")]


def ctype(a, event=False):
    if a.type == "int" or a.type == "fd":
        return "int32_t "
    if a.type == "uint":
        return "uint32_t "
    if a.type == "fixed":
        return "wl_fixed_t "
    if a.type == "string":
        return "const char *"
    if a.type == "array":
        return "struct wl_array *"
    if a.type in ("object", "new_id"):
        if a.interface:
            return f"struct {a.interface} *"
        return "void *"
    raise ValueError(a.type)


def referenced(interfaces):
    names = set()
    for i in interfaces:
        for m in i.requests + i.events:
            for a in m.args:
                if a.type in ("object", "new_id") and a.interface:
                    names.add(a.interface)
    return names


def client_header(name, interfaces):
    out = [f"/* Generated by wayland-scanner {VERSION} */", "", f"#ifndef {name.upper()}_CLIENT_PROTOCOL_H",
           f"#define {name.upper()}_CLIENT_PROTOCOL_H", "", "#include <stdint.h>", "#include <stddef.h>",
           '#include "wayland-client.h"', "", "#ifdef  __cplusplus", 'extern "C" {', "#endif", ""]
    for n in sorted(referenced(interfaces) | {i.name for i in interfaces}):
        out.append(f"struct {n};")
    out.append("")
    for i in interfaces:
        u = i.name.upper()
        out += [f"#ifndef {u}_INTERFACE", f"#define {u}_INTERFACE",
                f"extern const struct wl_interface {i.name}_interface;", "#endif"]
    out.append("")
    for i in interfaces:
        u = i.name.upper()
        for en, entries in i.enums:
            eu = f"{u}_{en.upper()}"
            out += [f"#ifndef {eu}_ENUM", f"#define {eu}_ENUM", f"enum {i.name}_{en} {{"]
            for ename, value, _ in entries:
                out.append(f"\t{eu}_{ename.upper()} = {value},")
            out.append("};")
            for ename, _, since in entries:
                if since > 1:
                    out.append(f"#define {eu}_{ename.upper()}_SINCE_VERSION {since}")
            out += [f"#endif /* {eu}_ENUM */", ""]
        if i.events:
            out.append(f"struct {i.name}_listener {{")
            for m in i.events:
                params = [f"void *data", f"struct {i.name} *{i.name}"]
                params += [f"{ctype(a, True)}{a.name}" for a in m.args]
                out.append(f"\tvoid (*{m.name})({', '.join(params)});")
            out += ["};", "",
                    "static inline int",
                    f"{i.name}_add_listener(struct {i.name} *{i.name},",
                    f"{' ' * (len(i.name) + 14)}const struct {i.name}_listener *listener, void *data)",
                    "{",
                    f"\treturn wl_proxy_add_listener((struct wl_proxy *) {i.name},",
                    "\t\t\t\t     (void (**)(void)) listener, data);",
                    "}", ""]
        for m in i.requests:
            out.append(f"#define {u}_{m.name.upper()} {m.opcode}")
        out.append("")
        for m in i.events:
            out.append(f"#define {u}_{m.name.upper()}_SINCE_VERSION {m.since}")
        for m in i.requests:
            out.append(f"#define {u}_{m.name.upper()}_SINCE_VERSION {m.since}")
        out += ["", "static inline void",
                f"{i.name}_set_user_data(struct {i.name} *{i.name}, void *user_data)", "{",
                f"\twl_proxy_set_user_data((struct wl_proxy *) {i.name}, user_data);", "}", "",
                "static inline void *", f"{i.name}_get_user_data(struct {i.name} *{i.name})", "{",
                f"\treturn wl_proxy_get_user_data((struct wl_proxy *) {i.name});", "}", "",
                "static inline uint32_t", f"{i.name}_get_version(struct {i.name} *{i.name})", "{",
                f"\treturn wl_proxy_get_version((struct wl_proxy *) {i.name});", "}", ""]
        has_destroy = any(m.name == "destroy" for m in i.requests)
        if not has_destroy and i.name != "wl_display":
            out += ["static inline void", f"{i.name}_destroy(struct {i.name} *{i.name})", "{",
                    f"\twl_proxy_destroy((struct wl_proxy *) {i.name});", "}", ""]
        for m in i.requests:
            nid = m.new_id
            if nid is None:
                ret = "void"
            elif nid.interface:
                ret = f"struct {nid.interface} *"
            else:
                ret = "void *"
            params = [f"struct {i.name} *{i.name}"]
            for a in m.args:
                if a.type == "new_id":
                    if not a.interface:
                        params.append("const struct wl_interface *interface")
                        params.append("uint32_t version")
                    continue
                params.append(f"{ctype(a)}{a.name}")
            out += ["static inline " + ret,
                    f"{i.name}_{m.name}({', '.join(params)})", "{"]
            proxy = f"(struct wl_proxy *) {i.name}"
            opc = f"{u}_{m.name.upper()}"
            if nid is not None:
                out.append("\tstruct wl_proxy *id;")
                out.append("")
                values = []
                for a in m.args:
                    if a.type == "new_id":
                        if not a.interface:
                            values += ["interface->name", "version"]
                        values.append("NULL")
                    else:
                        values.append(a.name)
                if nid.interface:
                    out.append(f"\tid = wl_proxy_marshal_constructor({proxy},")
                    out.append(f"\t\t\t {opc}, &{nid.interface}_interface, {', '.join(values)});")
                    out += ["", f"\treturn (struct {nid.interface} *) id;"]
                else:
                    out.append(f"\tid = wl_proxy_marshal_constructor_versioned({proxy},")
                    out.append(f"\t\t\t {opc}, interface, version, {', '.join(values)});")
                    out += ["", "\treturn (void *) id;"]
            else:
                values = "".join(f", {a.name}" for a in m.args)
                out.append(f"\twl_proxy_marshal({proxy},")
                out.append(f"\t\t\t {opc}{values});")
                if m.destructor:
                    out += ["", f"\twl_proxy_destroy({proxy});"]
            out += ["}", ""]
    out += ["#ifdef  __cplusplus", "}", "#endif", "", "#endif", ""]
    return "\n".join(out)


def code(name, interfaces, public):
    vis = "WL_EXPORT" if public else "WL_PRIVATE"
    out = [f"/* Generated by wayland-scanner {VERSION} */", "", "#include <stdlib.h>", "#include <stdint.h>",
           '#include "wayland-util.h"', ""]
    if not public:
        out += ["#ifndef __has_attribute", "# define __has_attribute(x) 0  /* Compatibility with non-clang compilers. */",
                "#endif", "", "#if (__has_attribute(visibility) || defined(__GNUC__) && __GNUC__ >= 4)",
                '#define WL_PRIVATE __attribute__ ((visibility("hidden")))', "#else", "#define WL_PRIVATE", "#endif",
                ""]
    for n in sorted(referenced(interfaces)):
        out.append(f"extern const struct wl_interface {n}_interface;")
    out.append("")
    # the types: a run of NULLs every message without interfaces shares, then each other message's own
    null_run = 0
    for i in interfaces:
        for m in i.requests + i.events:
            if m.all_null:
                null_run = max(null_run, m.type_count())
    types = ["NULL"] * null_run
    for i in interfaces:
        for m in i.requests + i.events:
            if m.all_null:
                m.type_index = 0
                continue
            m.type_index = len(types)
            for a in m.args:
                if a.type == "new_id" and not a.interface:
                    types += ["NULL", "NULL", "NULL"]
                elif a.type in ("object", "new_id") and a.interface:
                    types.append(f"&{a.interface}_interface")
                else:
                    types.append("NULL")
    out.append(f"static const struct wl_interface *{name}_types[] = {{")
    out += [f"\t{t}," for t in types]
    out += ["};", ""]
    for i in interfaces:
        for kind, msgs in (("requests", i.requests), ("events", i.events)):
            if not msgs:
                continue
            out.append(f"static const struct wl_message {i.name}_{kind}[] = {{")
            for m in msgs:
                out.append(f'\t{{ "{m.name}", "{m.signature()}", {name}_types + {m.type_index} }},')
            out += ["};", ""]
        req = f"{len(i.requests)}, {i.name}_requests" if i.requests else "0, NULL"
        ev = f"{len(i.events)}, {i.name}_events" if i.events else "0, NULL"
        out += [f"{vis} const struct wl_interface {i.name}_interface = {{", f'\t"{i.name}", {i.version},',
                f"\t{req},", f"\t{ev},", "};", ""]
    return "\n".join(out)


def main(argv):
    if argv[:1] in (["--version"], ["-v"]):
        print(f"wayland-scanner {VERSION}", file=sys.stderr)
        return 0
    args = [a for a in argv if not a.startswith("-")]
    if len(args) != 3:
        print(__doc__, file=sys.stderr)
        return 1
    mode, src, dst = args
    name, interfaces = parse(src)
    if mode == "client-header":
        text = client_header(name, interfaces)
    elif mode in ("private-code", "code", "public-code"):
        text = code(name, interfaces, mode == "public-code")
    else:
        print(f"wayland_scanner: {mode} is not supported", file=sys.stderr)
        return 1
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
