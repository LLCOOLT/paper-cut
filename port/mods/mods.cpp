// $TTYD_TRACE: each tag a mod answered, once (local_ci's mods stage)
static const char* traced(const char* tag, const char* text) {
  static const bool trace = getenv("TTYD_TRACE") != nullptr;
  static std::unordered_map<std::string, bool> seen;
  if (trace && !seen[tag]) {
    seen[tag] = true;
    printf("[trace] mod message %s\n", tag);
    fflush(stdout);
  }
  return text;
}

void portModsSetHostFile(const char* discPath, const void* data, size_t size) {
  const uint8_t* p = static_cast<const uint8_t*>(data);
  sHostFiles[discPath[0] == '/' ? discPath : std::string("/") + discPath] = std::vector<uint8_t>(p, p + size);
}

