void* portModsMapScript(const char* map) {
  std::lock_guard lock(sMapLock);
  const auto it = sMaps.find(map);
  return it == sMaps.end() ? nullptr : it->second.script;
}

const char* portModsPathAlias(const char* path) {
  std::lock_guard lock(sMapLock);
  if (sAliases.empty()) {
    return path;
  }
  static thread_local std::string out;
  out = path;
  for (const auto& [from, to] : sAliases) {
    const std::string bare = from.substr(1); // "m/gor_99/" at the start too
    if (const size_t at = out.find(from); at != std::string::npos) {
      out.replace(at, from.size(), to);
      return out.c_str();
    }
    if (out.compare(0, bare.size(), bare) == 0) {
      out.replace(0, bare.size(), to.substr(1));
      return out.c_str();
    }
  }
  return path;
}

const char* portModMsgSearch(const char* tag, const char* langDir) {
  std::lock_guard lock(sMessageLock);
  if (!sCodeMessages.empty()) {
    if (const auto it = sCodeMessages.find(tag); it != sCodeMessages.end()) {
      return traced(tag, it->second);
    }
  }
  if (sMessages == nullptr || sMessages->empty()) {
    return nullptr;
  }
  for (const std::string& lang : {languageCode(langDir), std::string()}) {
    const auto table = sMessages->find(lang);
    if (table != sMessages->end()) {
      const auto it = table->second.find(tag);
      if (it != table->second.end()) {
        return traced(tag, it->second.c_str());
      }
    }
  }
  return nullptr;
}

